import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import type { Client } from "pg";
import type * as Live from "../../app/bingo/live/repository.server";
import type * as Preparation from "../../app/bingo/preparation/repository.server";
import type * as Games from "../../app/games/gameDraftRepository.server";
import type { LiveCommand } from "../../app/bingo/live/live";

/** Called inside the real AP2 PostgreSQL fixture, retaining frozen fonts/logo versions. */
export async function exerciseBingoLive(db: Client, live: typeof Live, preparation: typeof Preparation, games: typeof Games) {
  const game = await games.writeGameDraft(1, "BINGO", { seriesId: 10, title: "AP3 isolated lifecycle", date: "", time: "" });
  await preparation.writePreparation(1, { gameId: game.id, expectedSeriesId: 10, revision: 0, operation: "createRound" });
  let prep = await preparation.readPreparation(1, game.id);
  const roundId = prep.rounds[0].id;
  await preparation.writePreparation(1, { gameId: game.id, expectedSeriesId: 10, revision: prep.revision, operation: "generate", roundId, count: 3, requestId: randomUUID() });
  prep = await preparation.readPreparation(1, game.id);
  assert.equal((await live.readGameAudience(1, game.id)).status, "PREPARED");
  assert.equal((await live.readGameAudience(1, game.id)).startedAt, 0);
  const before = (await db.query("SELECT to_jsonb(c) AS data FROM pubquiz.bingo_cards c ORDER BY id")).rows;
  const start = { gameId: game.id, roundId, requestId: randomUUID(), expectedSeriesId: 10, preparationRevision: prep.revision };
  const starts = await Promise.all([live.startLive(1, start), live.startLive(1, start)]);
  assert.equal(starts[0].runId, starts[1].runId);
  const runId = starts[0].runId;
  await assert.rejects(db.query(`INSERT INTO pubquiz.bingo_live_runs
    (id,game_id,round_id,eventreihe_id,status,revision,started_at,created_by,round_snapshot,design_snapshot,visual_assets,audience_key,start_request_id,start_request_hash)
    SELECT $2,game_id,round_id,eventreihe_id,status,revision,started_at,created_by,round_snapshot,design_snapshot,visual_assets,$3,$4,start_request_hash
    FROM pubquiz.bingo_live_runs WHERE id=$1`, [runId, randomUUID(), randomUUID(), randomUUID()]), { code: "23505" }, "database independently rejects a second active run");
  await assert.rejects(live.startLive(1, { ...start, requestId: randomUUID() }), /ACTIVE_RUN_EXISTS/);
  await assert.rejects(live.startLive(1, { ...start, preparationRevision: 999 }), /REQUEST_REUSED/);
  const view = () => live.readLive(1, game.id, runId);
  const request = async (command: LiveCommand) => ({ gameId: game.id, runId, requestId: randomUUID(), revision: (await view()).live!.revision, command });
  const send = async (command: LiveCommand) => { const r = await request(command); await live.commandLive(1, r); return r.requestId; };
  for (const userId of [2, 3, 4, 5, 6]) {
    await assert.rejects(live.readLive(userId, game.id));
    await assert.rejects(live.commandLive(userId, await request({ kind: "pause" })));
  }
  await assert.rejects(live.readLive(1, game.id, randomUUID()), /RUN_NOT_FOUND/);
  const original = (await view()).live!, card = original.cards[0];
  assert.equal(original.round.issued, null);
  await preparation.writePreparation(1, { gameId: game.id, expectedSeriesId: 10, revision: (await preparation.readPreparation(1, game.id)).revision, operation: "saveRound", roundId, label: "Later preparation", target: 20, strategy: "NEW", issued: 0 });
  assert.equal((await view()).live!.round.label, original.round.label);
  assert.equal((await view()).live!.round.issued, null);
  assert.deepEqual((await view()).live!.design, original.design);
  const invalidCall = await send({ kind: "call", stage: "BINGO" });
  const foreign = (await db.query("SELECT c.id,c.series_id FROM pubquiz.bingo_cards c JOIN pubquiz.bingo_card_series s ON s.id=c.series_id WHERE s.game_id<>$1 LIMIT 1", [game.id])).rows[0];
  assert.ok(foreign);
  await assert.rejects(live.commandLive(1, await request({ kind: "identify", callId: invalidCall, cardId: foreign.id })), /CARD_OR_CALL_NOT_FOUND/);
  await assert.rejects(db.query("INSERT INTO pubquiz.bingo_live_cards(run_id,game_id,card_id,series_id) VALUES($1,$2,$3,$4)", [runId, game.id, foreign.id, foreign.series_id]), { code: "23503" });
  await preparation.writePreparation(1, { gameId: game.id, expectedSeriesId: 10, revision: (await preparation.readPreparation(1, game.id)).revision, operation: "createRound" });
  const unassignedRound = (await preparation.readPreparation(1, game.id)).rounds[1].id;
  const unassigned = await preparation.writePreparation(1, { gameId: game.id, expectedSeriesId: 10, revision: (await preparation.readPreparation(1, game.id)).revision, operation: "generate", roundId: unassignedRound, count: 1, requestId: randomUUID() });
  const unassignedCard = (await preparation.readCards(1, game.id, unassigned.seriesId!)).cards[0];
  await assert.rejects(live.commandLive(1, await request({ kind: "identify", callId: invalidCall, cardId: unassignedCard.id })), /CARD_OR_CALL_NOT_FOUND/);
  assert.equal((await view()).live!.cards.length, original.cards.length, "later preparation does not expand frozen inventory");
  const numbers = card.cells.slice(0, 3).flat().filter((n): n is number => n !== null);
  for (const number of numbers.slice(0, 5)) await send({ kind: "draw", number });
  await send({ kind: "identify", callId: invalidCall, cardId: card.id });
  await assert.rejects(live.commandLive(1, await request({ kind: "decide", callId: invalidCall, action: "CONFIRM", reason: "Too late" })), /CLAIM_NOT_COVERED/);
  await send({ kind: "decide", callId: invalidCall, action: "REJECT", reason: "At call cutoff no line" });
  const claim = async (stage: "BINGO" | "DOUBLE" | "TRIPLE") => {
    const id = await send({ kind: "call", stage });
    await assert.rejects(live.commandLive(1, await request({ kind: "identify", callId: id, cardId: randomUUID() })), /CARD_OR_CALL_NOT_FOUND/);
    await send({ kind: "identify", callId: id, cardId: card.id });
    return id;
  };
  const bingo = await claim("BINGO");
  const decision = await request({ kind: "decide", callId: bingo, action: "CONFIRM", reason: "First full row" });
  const parallel = await Promise.allSettled([live.commandLive(1, decision), live.commandLive(1, { ...decision, requestId: randomUUID() })]);
  assert.equal(parallel.filter(r => r.status === "fulfilled").length, 1);
  const committed = parallel[0].status === "fulfilled" ? decision : { ...decision, requestId: (await view()).live!.events.at(-1)!.id };
  await live.commandLive(1, committed);
  await assert.rejects(live.commandLive(1, { ...committed, command: { kind: "pause" } }), /REQUEST_REUSED/);
  for (const number of numbers.slice(5, 10)) await send({ kind: "draw", number });
  const double = await claim("DOUBLE");
  await send({ kind: "decide", callId: double, action: "CONFIRM", reason: "Two rows" });
  for (const number of numbers.slice(10)) await send({ kind: "draw", number });
  const triple = await claim("TRIPLE");
  await send({ kind: "decide", callId: triple, action: "CONFIRM", reason: "Three rows" });
  const unused = Array.from({ length: 75 }, (_, i) => i + 1).find(n => !numbers.includes(n))!;
  await send({ kind: "correct", number: unused, reason: "Last physical ball was misentered" });
  assert.equal((await view()).live!.state.run.rounds[0].claims.find(c => c.id === triple)!.needsReview, true);
  await send({ kind: "decide", callId: triple, action: "REVOKE", reason: "Explicit review" });
  const used = (await view()).live!.state.run.rounds[0].draws.map(d => d.number);
  const remaining = Array.from({ length: 75 }, (_, i) => i + 1).filter(n => !used.includes(n));
  const raceOne = await request({ kind: "draw", number: remaining[0] });
  const raceTwo = { ...raceOne, requestId: randomUUID(), command: { kind: "draw" as const, number: remaining[1] } };
  const drawRace = await Promise.allSettled([live.commandLive(1, raceOne), live.commandLive(1, raceTwo)]);
  assert.equal(drawRace.filter(r => r.status === "fulfilled").length, 1);
  await assert.rejects(live.commandLive(1, await request({ kind: "draw", number: used[0] })), /DUPLICATE_DRAW_NUMBER/);
  const paused = await request({ kind: "pause" });
  await live.commandLive(1, paused); await live.commandLive(1, paused);
  await assert.rejects(live.commandLive(1, await request({ kind: "draw", number: 75 })), /RUN_NOT_RUNNING/);
  const elapsed = (await view()).live!.elapsedMs;
  assert.equal((await view()).live!.elapsedMs, elapsed);
  await send({ kind: "target", number: 50 });
  await send({ kind: "resume" });
  const audience = await live.readAudience(1, original.audienceKey);
  assert.equal((await live.readGameAudience(1, game.id)).id, runId);
  assert.equal(audience.revision, (await view()).live!.revision);
  assert.equal("cards" in audience, false); assert.equal("events" in audience, false);
  const font = await live.readLiveAsset(1, original.audienceKey, "body"); assert.ok(font.bytes.length > 1000);
  const revision = (await view()).live!.revision;
  await live.readAudience(1, original.audienceKey); await view();
  assert.equal((await view()).live!.revision, revision, "reads do not mutate");
  await db.query("INSERT INTO pubquiz.benutzer_reihenrollen(benutzer_id,eventreihe_id,rolle) VALUES(3,10,'EVENT_MANAGER')");
  await live.readLive(3, game.id, runId); await live.readAudience(3, original.audienceKey);
  const revokedRequest = await request({ kind: "target", number: 60 });
  await db.query("DELETE FROM pubquiz.benutzer_reihenrollen WHERE benutzer_id=3 AND eventreihe_id=10");
  await assert.rejects(live.commandLive(3, revokedRequest));
  await assert.rejects(live.readLive(3, game.id, runId)); await assert.rejects(live.readAudience(3, original.audienceKey));
  await db.query("UPDATE pubquiz.eventreihen SET ist_archiviert=true WHERE eventreihe_id=10");
  await assert.rejects(live.commandLive(1, await request({ kind: "pause" })));
  await db.query("UPDATE pubquiz.eventreihen SET ist_archiviert=false WHERE eventreihe_id=10");
  await db.query("UPDATE pubquiz.eventreihe_eventarten SET ist_freigeschaltet=false WHERE eventreihe_id=10 AND eventart='BINGO'");
  await assert.rejects(view()); await assert.rejects(live.readAudience(1, original.audienceKey));
  await assert.rejects(live.commandLive(1, { gameId: game.id, runId, requestId: randomUUID(), revision, command: { kind: "pause" } }));
  await db.query("UPDATE pubquiz.eventreihe_eventarten SET ist_freigeschaltet=true WHERE eventreihe_id=10 AND eventart='BINGO'");
  await send({ kind: "end" });
  await assert.rejects(live.commandLive(1, await request({ kind: "resume" })), /RUN_ENDED/);
  await assert.rejects(db.query("UPDATE pubquiz.bingo_live_events SET actor_id=2 WHERE run_id=$1", [runId]), { code: "23514" });
  await assert.rejects(db.query("DELETE FROM pubquiz.bingo_live_cards WHERE run_id=$1", [runId]), { code: "23514" });
  await assert.rejects(db.query("UPDATE pubquiz.bingo_live_runs SET round_snapshot='{}'::jsonb WHERE id=$1", [runId]), { code: "23514" });
  assert.deepEqual((await db.query("SELECT to_jsonb(c) AS data FROM pubquiz.bingo_cards c WHERE id=ANY($1::uuid[]) ORDER BY id", [before.map(r => r.data.id)])).rows, before);
  assert.equal((await view()).live!.state.run.status, "ENDED");
  // New run has its own identity and can freeze the same existing immutable cards.
  const next = await live.startLive(1, { ...start, preparationRevision: (await preparation.readPreparation(1, game.id)).revision, requestId: randomUUID() });
  assert.notEqual(next.runId, runId);
  assert.equal((await live.readLive(1, game.id, next.runId)).live!.round.issued, 0, "zero issuance stays distinct from not recorded");
  assert.equal((await live.readGameAudience(1, game.id)).id, next.runId);
  assert.ok((await live.readGameAudience(1, game.id)).startedAt > original.startedAt);
  console.info("AP3 real PostgreSQL lifecycle, call cutoffs, decisions, retries, fresh authorization and immutable AP2 cards: PASS");
}
